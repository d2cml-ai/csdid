def _panel():
    rng = np.random.default_rng(74088)
    n, periods = 180, 6
    ids = np.repeat(np.arange(n), periods)
    t = np.tile(np.arange(1, periods + 1), n)
    g = np.repeat(np.repeat([0, 3, 5], n // 3), periods)
    x = np.repeat(rng.normal(size=n), periods) + rng.normal(size=len(t)) * .15
    cat = np.array(["a", "b", "c"])[ids % 3]
    cluster = ids % 18
    shocks = rng.normal(size=(18, periods))
    y = (np.repeat(rng.normal(size=n), periods) + .2 * t + .3 * x * t
         + .1 * (cat == "b") * t - .2 * (cat == "c") * t
         + (g > 0) * (t >= g) * (1 + .1 * (t - g))
         + shocks[cluster, t - 1] + rng.normal(scale=.2, size=len(t)))
    return pd.DataFrame({"id": ids, "period": t, "G": g, "Y": y, "X": x,
                         "cat": cat, "dummy_b": (cat == "b").astype(float),
                         "dummy_c": (cat == "c").astype(float),
                         "cluster": cluster, "region": ids % 13,
                         "weight": 1 + t / 10 + rng.uniform(0, .2, len(t))})


def _fit(data, faster=False, method="dr", base="varying", **kwargs):
    args = dict(yname="Y", tname="period", idname="id", gname="G", data=data,
                xformla="Y~X", faster_mode=faster)
    args.update(kwargs)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return ATTgt(**args).fit(est_method=method, base_period=base, bstrap=False)


def _same_result(left, right):
    for key in ("group", "t"):
        np.testing.assert_array_equal(left.MP[key], right.MP[key])
    assert left.MP["n"] == right.MP["n"]
    for key in ("att", "se"):
        np.testing.assert_array_equal(np.isnan(left.results[key]), np.isnan(right.results[key]))
        np.testing.assert_allclose(left.results[key], right.results[key], rtol=1e-10,
                                   atol=1e-11, equal_nan=True)
    np.testing.assert_allclose(left.MP["inffunc"]["inffunc"],
                               right.MP["inffunc"]["inffunc"],
                               rtol=1e-10, atol=1e-11, equal_nan=True)


@pytest.mark.parametrize("faster", [False, True])
@pytest.mark.parametrize("method", ["dr", "reg", "ipw"])
@pytest.mark.parametrize("route", ["varying_weights", "unbalanced", "compound", "rc"])
def test_point_only_nondefault_routes_preserve_all_att(faster, method, route):
    """R test-compute-inffunc: skip inference across all supported designs."""
    data = _panel()
    args = {}
    if route == "varying_weights":
        args.update(weights_name="weight", fix_weights="varying")
    elif route == "unbalanced":
        data = data.loc[~((data.id % 11 == 0) & (data.period == 2))].copy()
        args["allow_unbalanced_panel"] = True
    elif route == "compound":
        args.update(anticipation=1, base="universal", control_group="notyettreated",
                    clustervar="cluster")
    else:
        args.update(panel=False, idname=None)
    full = _fit(data, faster, method, **args)
    point = _fit(data, faster, method, compute_inffunc=False, cband=True, **args)
    np.testing.assert_array_equal(full.MP["group"], point.MP["group"])
    np.testing.assert_array_equal(full.MP["t"], point.MP["t"])
    np.testing.assert_array_equal(np.isnan(full.MP["att"]), np.isnan(point.MP["att"]))
    np.testing.assert_allclose(full.MP["att"], point.MP["att"], rtol=0, atol=1e-12,
                               equal_nan=True)
    assert np.isfinite(point.MP["att"]).any()
    assert np.isnan(point.results["se"]).all()
    assert np.isnan(point.results["c"])
    assert point.MP["inffunc"] is None
    assert point.MP["W"] is None and point.MP["Wpval"] is None
    assert point.dp["bstrap"] is False and point.dp["cband"] is False
    point.summ_attgt()
    assert len(point.summary2) == len(point.MP["att"])
    assert point.summary2["Std. Error"].isna().all()


