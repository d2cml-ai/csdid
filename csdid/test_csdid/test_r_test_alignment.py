@pytest.mark.parametrize("faster", [False, True])
@pytest.mark.parametrize("method", ["dr", "reg", "ipw"])
@pytest.mark.parametrize("selection", ["unused_first", "unused_last", "missing", "balanced"])
def test_unused_factor_levels_equal_explicit_retained_sample(faster, method, selection):
    """R test-modelmatrix-hoist: globally empty levels must not invalidate cells."""
    data = _panel()
    levels = ["unused", "a", "b", "c"] if selection == "unused_first" else ["a", "b", "c", "unused"]
    data["cat"] = pd.Categorical(data.cat, categories=levels)
    args = {}
    if selection == "missing":
        data.loc[data.cat == "c", "Y"] = np.nan
        reference = data.loc[data.cat != "c"].copy()
    elif selection == "balanced":
        data = data.loc[~((data.cat == "c") & (data.period == 2))].copy()
        reference = data.loc[data.cat != "c"].copy()
        args["allow_unbalanced_panel"] = False
    else:
        reference = data.copy()
    reference["cat"] = reference.cat.cat.remove_unused_categories()
    data = data.sample(frac=1, random_state=98)
    # Nontrivial caller indices exercise row tracking through balancing.
    data.index = pd.Index(np.arange(len(data)) * 19 + 7, name="caller_row")
    before = data.copy(deep=True)
    actual = _fit(data, faster, method, xformla="Y~C(cat)+X", **args)
    expected = _fit(reference, faster, method, xformla="Y~C(cat)+X", **args)
    assert np.isfinite(actual.MP["att"]).all()
    _same_result(actual, expected)
    pd.testing.assert_frame_equal(data, before, check_exact=True)
    assert all(isinstance(column, str) for column in actual.dp["data"].columns)


