def test_bootstrap_postprocess_matches_independent_quantile_formula():
    """R test-mboot-postprocess: pin IQR scaling, live dimensions, and max statistic."""
    influence = np.column_stack([np.random.default_rng(201).normal(size=(80, 3)),
                                 np.zeros(80)])
    dp = dict(data=pd.DataFrame({"id": np.arange(80), "period": 1}),
              idname="id", clustervars=None, biters=199, alp=.1, panel=True,
              tname="period", true_repeated_cross_sections=False)
    np.random.seed(303)
    result = mboot(influence, dp)
    draws = result["bres"]
    assert draws.shape == (199, 3)
    scale = (np.quantile(draws, .75, axis=0, method="inverted_cdf")
             - np.quantile(draws, .25, axis=0, method="inverted_cdf"))
    scale /= norm.ppf(.75) - norm.ppf(.25)
    critical = np.quantile(np.max(np.abs(draws / scale), axis=1), .9,
                           method="inverted_cdf")
    np.testing.assert_allclose(result["se"][:3], scale / np.sqrt(80), rtol=0, atol=1e-14)
    np.testing.assert_allclose(result["crit_val"], critical, rtol=0, atol=1e-14)
    assert np.isnan(result["se"][3])
