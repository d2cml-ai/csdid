@pytest.mark.parametrize("unbalanced", [False, True])
def test_shuffled_clustered_panel_matches_cluster_sum_oracle_and_all_aggregations(unbalanced):
    """R test-unbalanced-faster-cluster-se: align IF rows before summing clusters."""
    data = _panel()
    if unbalanced:
        data = data.loc[~((data.id % 11 == 0) & (data.period == 2))].copy()
    data = data.sample(frac=1, random_state=248)
    slow = _fit(data, False, base="universal", clustervar="cluster",
                allow_unbalanced_panel=unbalanced)
    fast = _fit(data, True, base="universal", clustervar="cluster",
                allow_unbalanced_panel=unbalanced)
    iid = _fit(data, True, base="universal", allow_unbalanced_panel=unbalanced)
    _same_result(slow, fast)
    labels = data.drop_duplicates("id").sort_values("id").cluster.to_numpy()
    influence = np.asarray(fast.MP["inffunc"]["inffunc"])
    assert len(labels) == influence.shape[0] == data.id.nunique()
    sums = np.stack([influence[labels == label].sum(axis=0) for label in np.unique(labels)])
    expected = np.sqrt((sums ** 2).sum(axis=0)) / len(labels)
    # Universal base cells have a constructed zero ATT and undefined SE.
    bases = np.asarray(fast.MP["t"]) == np.asarray(fast.MP["group"]) - 1
    expected[bases] = np.nan
    np.testing.assert_array_equal(np.isnan(fast.results["se"]), bases)
    np.testing.assert_allclose(fast.results["se"], expected, rtol=0, atol=1e-12,
                               equal_nan=True)
    assert np.max(np.abs(np.asarray(fast.results["se"])[~bases]
                         - np.asarray(iid.results["se"])[~bases])) > 1e-6
    for typec in ("simple", "group", "dynamic", "calendar"):
        left = _aggregate(slow, typec=typec)
        right = _aggregate(fast, typec=typec)
        for key in ("egt", "att_egt", "se_egt", "overall_att", "overall_se"):
            if left.get(key) is not None:
                np.testing.assert_allclose(left[key], right[key], rtol=1e-10,
                                           atol=1e-11, equal_nan=True)


