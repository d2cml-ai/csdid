@pytest.mark.parametrize("faster", [False, True])
@pytest.mark.parametrize("route", ["unbalanced", "rc"])
@pytest.mark.parametrize("missing_value", [np.nan, None])
def test_partial_missing_custom_influence_propagates_to_unit_and_se(faster, route, missing_value):
    """R test-faster-mode-consistency: observed missing IF must not become zero."""
    data = _panel()
    args = {}
    if route == "unbalanced":
        data = data.loc[~((data.id % 11 == 0) & (data.period == 2))].copy()
        args["allow_unbalanced_panel"] = True
    else:
        args.update(panel=False, idname=None)

    def partial_na(y, post, D, i_weights, covariates):
        att, influence = reg_did.reg_did_rc(y, post, D, i_weights=i_weights,
                                           covariates=covariates)
        influence = np.asarray(influence).copy()
        influence[0] = missing_value
        return att, influence

    expected = _fit(data, faster, "reg", **args)
    actual = _fit(data, faster, partial_na, **args)
    np.testing.assert_allclose(actual.MP["att"], expected.MP["att"], rtol=0, atol=1e-12)
    assert np.isfinite(actual.MP["att"]).all()
    assert np.isnan(actual.results["se"]).all()
    influence = actual.MP["inffunc"]["inffunc"]
    np.testing.assert_array_equal(np.isnan(influence).sum(axis=0),
                                   np.ones(len(actual.MP["att"]), dtype=int))
    # Retain every healthy contribution, including zeros for units absent from a cell.
    healthy = ~np.isnan(influence)
    np.testing.assert_array_equal(influence[healthy], expected.MP["inffunc"]["inffunc"][healthy])


